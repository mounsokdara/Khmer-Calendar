const weekdaysMonEn = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

Lang deviceLang() {
  try {
    final locale = IntlHelper.localeName;
    return locale.toLowerCase().startsWith('km') ? Lang.km : Lang.en;
  } catch (_) {
    return Lang.km;
  }
}

class IntlHelper {
  static String localeName = 'km';
}

Lang resolveLang(String pref) => pref == 'auto' ? deviceLang() : (pref == 'en' ? Lang.en : Lang.km);

String t(Lang lang, String key) {
  final dict = lang == Lang.en ? en : km;
  return dict[key] ?? key;
}

List<String> monthsOf(Lang lang) => lang == Lang.en ? monthsEn : monthsKm;
List<String> weekdaysFull(Lang lang) => lang == Lang.en ? weekdaysFullEn : weekdaysFullKm;

List<String> weekdaysStarting(Lang lang, int start) {
  final src = List<String>.from(lang == Lang.en ? weekdaysMonEn : weekdaysMonKm);
  if (start == 1) return src;
  if (start == 6) return [src[5], src[6], ...src.sublist(0, 5)];
  return [src[6], ...src.sublist(0, 6)];
}
