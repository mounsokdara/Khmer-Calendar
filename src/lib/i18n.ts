export function deviceLang(): Lang {
  if (typeof navigator === "undefined") return "km";
  return (navigator.language || "km").toLowerCase().startsWith("km") ? "km" : "en";
}
export function resolveLang(pref: LangPref): Lang {
  return pref === "auto" ? deviceLang() : pref;
}
export function t(lang: Lang, key: Msg): string {
  const dict: Record<string, string> = lang === "en" ? EN : KM;
  return dict[key] ?? String(key);
}
